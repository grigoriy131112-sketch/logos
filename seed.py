REACTIONS = [
    (0, ["like", "insight", "thanks"]),
    (1, ["like", "thanks"]),
    (2, ["insight", "think", "like"]),
    (3, ["like"]),
    (4, ["thanks", "insight"]),
]


def main():
    app = create_app()
    with app.app_context():
        if db.list_posts():
            print("В базе уже есть публикации — наполнение пропущено.")
            return
        ids = []
        for item in POSTS:
            ids.append(db.create_post(
                item["title"], item["body"],
                author=item["author"], tags=item["tags"], summary=item["summary"],
            ))
        for idx, body, author in COMMENTS:
            db.add_comment(ids[idx], body, author=author)
        for idx, kinds in REACTIONS:
            for kind in kinds:
                db.add_reaction(ids[idx], kind)
        print(f"Добавлено публикаций: {len(POSTS)}, откликов: {len(COMMENTS)}.")


if __name__ == "__main__":
    main()
