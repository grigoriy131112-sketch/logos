def main():
    app = create_app()
    with app.app_context():
        if db.list_posts():
            print("В базе уже есть публикации — наполнение пропущено.")
            return
        for item in POSTS:
            db.create_post(
                item["title"], item["body"],
                author=item["author"], tags=item["tags"], summary=item["summary"],
            )
        first = db.list_posts()[-1]
        db.add_comment(
            first["id"],
            "Отличное начало! Особенно про паузы между абзацами.",
            author="Читатель",
        )
        print(f"Добавлено публикаций: {len(POSTS)}.")


if __name__ == "__main__":
    main()
